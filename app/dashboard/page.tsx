import { Activity, DollarSign, Package, ShoppingCart, TrendingUp } from "lucide-react";
import Link from "next/link";
import { EmptyState } from "@/components/dashboard/EmptyState";
import { MetricCard } from "@/components/dashboard/MetricCard";
import { PageHeader } from "@/components/dashboard/PageHeader";
import { Button } from "@/components/ui/button";
import { requireAuthenticatedShop } from "@/lib/dashboard/auth";
import { getDashboardOverview, getRecentBundles } from "@/services/dashboard/overview";

function formatCurrency(value: number | null): string | null {
  if (value === null) return null;
  return new Intl.NumberFormat("en-US", { style: "currency", currency: "USD" }).format(value);
}

function formatPercent(value: number | null): string | null {
  if (value === null) return null;
  return new Intl.NumberFormat("en-US", { style: "percent", maximumFractionDigits: 1 }).format(
    value,
  );
}

export default async function DashboardHomePage() {
  const shop = await requireAuthenticatedShop();
  const [overview, recentBundles] = await Promise.all([
    getDashboardOverview(shop.id),
    getRecentBundles(shop.id),
  ]);

  return (
    <div className="space-y-8">
      <PageHeader
        title="Home"
        description="An overview of your bundle performance."
        action={
          <Button asChild>
            <Link href="/dashboard/bundles/create">Create bundle</Link>
          </Button>
        }
      />

      <div className="grid grid-cols-1 gap-4 sm:grid-cols-2 lg:grid-cols-4">
        <MetricCard
          label="Bundle revenue"
          value={formatCurrency(overview.totalRevenue)}
          icon={DollarSign}
          helpText="Revenue generated by bundle purchases"
        />
        <MetricCard
          label="Active bundles"
          value={String(overview.activeBundleCount)}
          icon={Package}
          helpText="Bundles currently published"
        />
        <MetricCard
          label="Orders"
          value={String(overview.orderCount)}
          icon={ShoppingCart}
          helpText="Bundle purchases"
        />
        <MetricCard
          label="Conversion rate"
          value={formatPercent(overview.conversionRate)}
          icon={TrendingUp}
          helpText="Purchases per bundle view"
        />
      </div>

      <section className="space-y-3">
        <h2 className="text-foreground text-sm font-semibold">Recent activity</h2>
        {recentBundles.length === 0 ? (
          <EmptyState
            icon={Activity}
            title="No activity yet"
            description="Once you create bundles and merchants start interacting with them, recent activity will show up here."
          />
        ) : (
          <ul className="divide-border border-border divide-y rounded-xl border">
            {recentBundles.map((bundle) => (
              <li key={bundle.id} className="flex items-center justify-between px-4 py-3 text-sm">
                <span className="text-foreground font-medium">{bundle.title}</span>
                <span className="text-muted-foreground">
                  Created{" "}
                  {new Intl.DateTimeFormat("en-US", { dateStyle: "medium" }).format(
                    bundle.createdAt,
                  )}
                </span>
              </li>
            ))}
          </ul>
        )}
      </section>
    </div>
  );
}
